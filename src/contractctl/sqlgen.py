"""
SQL generation: compiles a contract into the SQL files the platform runs.

  pipeline SQL (Lakeflow Spark Declarative Pipelines)
    bronze  streaming table over the landing volume, everything as STRING
    silver  private "checked" table (casting + verdict + expectations),
            the data product (compliant rows) and the quarantine (violations + reasons)
    gold    materialized view = contract envelope around hand-written business logic

  job SQL (SQL warehouse, after every pipeline run; parameters :catalog, :git_commit, :run_id)
    governance  contract registry, rules, tags, certification badge, grants
    sla         freshness + table-level checks, results to UC, raise_error on breach

Pipeline SQL uses two-part names (schema.table); the catalog is the pipeline's default
catalog. ${contracts.catalog} and ${contracts.landing} are pipeline configuration values.
"""
from __future__ import annotations

from .model import Contract, Rule

CATALOG = "${contracts.catalog}"
LANDING = "${contracts.landing}"


# ── helpers ───────────────────────────────────────────────────────────────────
def lit(value) -> str:
    """SQL string literal."""
    return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"


def ident(name: str) -> str:
    return f"`{name}`"


def header(c: Contract, what: str) -> str:
    return (
        "-- " + "=" * 76 + "\n"
        f"-- GENERATED by contractctl from {c.rel_path}\n"
        f"-- Contract {c.id} v{c.version}: {what}\n"
        "-- Do not edit: change the contract and run `contractctl generate`.\n"
        "-- " + "=" * 76 + "\n"
    )


def tblproperties(c: Contract, role: str) -> str:
    props = {
        "contract.id": c.id,
        "contract.version": c.version,
        "contract.status": c.status,
        "contract.owner_team": c.team_name,
        "contract.source": c.rel_path,
        "contract.table_role": role,
    }
    body = ",\n".join(f"  {lit(k)} = {lit(v)}" for k, v in props.items())
    return f"TBLPROPERTIES (\n{body}\n)"


def table_comment(c: Contract) -> str:
    d = c.description
    parts = [str(d.get("purpose", "")).strip()]
    if d.get("usage"):
        parts.append("Usage: " + str(d["usage"]).strip())
    if d.get("limitations"):
        parts.append("Limitations: " + str(d["limitations"]).strip())
    parts.append(f"Owner: {c.team_name}. Contract {c.id} v{c.version}.")
    return " ".join(p for p in parts if p)


def qualify(fn: str) -> str:
    """Policy functions are catalog-relative in contracts: governance.mask_email."""
    return fn if fn.count(".") >= 2 else f"{CATALOG}.{fn}"


def expectation(rule: Rule, layer: str, observe_only: bool) -> str:
    clause = f"  CONSTRAINT {rule.name} EXPECT ({rule.safe_expression})"
    if rule.action == "fail":
        return clause + " ON VIOLATION FAIL UPDATE"
    if rule.action == "drop" and not observe_only:
        return clause + " ON VIOLATION DROP ROW"
    return clause


def column_ddl(c: Contract, prop: dict, cfg: dict) -> str:
    ddl = f"  {prop['name']} {prop['physicalType']}"
    if prop.get("required"):
        ddl += " NOT NULL"
    if prop.get("description"):
        ddl += f" COMMENT {lit(prop['description'])}"
    mask = c.mask_for(prop, cfg["default_pii_mask"])
    if mask:
        ddl += f" MASK {qualify(mask)}"
    return ddl


def pk_ddl(c: Contract) -> list[str]:
    pk = c.primary_key()
    return [f"  CONSTRAINT {c.table}_pk PRIMARY KEY ({', '.join(pk)})"] if pk else []


def row_filter_clause(c: Contract) -> str:
    rf = c.row_filter
    if not rf:
        return ""
    return f"WITH ROW FILTER {qualify(rf['function'])} ON ({', '.join(rf['columns'])})\n"


# ── pipeline SQL ──────────────────────────────────────────────────────────────
def bronze_sql(c: Contract, cfg: dict) -> str:
    s = cfg["schemas"]
    src = c.source
    src_path = src.get("path")
    read_schema = ", ".join(f"{p['name']} STRING" for p in c.source_properties())
    return (
        header(c, "BRONZE ingestion")
        + "-- Files as delivered by the source system. Every column is read as STRING and\n"
        "-- nothing is rejected: unexpected fields are kept in _rescued_data.\n"
        f"CREATE OR REFRESH STREAMING TABLE {s['bronze']}.{c.table}_raw\n"
        f"COMMENT {lit(f'Raw {c.table} as delivered to the landing volume ({src_path}). Source of contract {c.id}.')}\n"
        f"{tblproperties(c, 'bronze')}\n"
        "AS SELECT\n"
        "  *,\n"
        "  current_timestamp() AS _ingested_at,\n"
        "  _metadata.file_path AS _source_file\n"
        "FROM STREAM read_files(\n"
        f"  '{LANDING}/{src.get('path', c.table)}',\n"
        f"  format => {lit(src.get('format', 'json'))},\n"
        f"  schema => {lit(read_schema)},\n"
        "  rescuedDataColumn => '_rescued_data'\n"
        ");\n"
    )


def silver_sql(c: Contract, cfg: dict) -> str:
    s = cfg["schemas"]
    rules = c.rules()
    checked = f"{c.table}_checked"
    src_props = c.source_properties()

    raw_struct = ", ".join(f"{lit(p['name'])}, {p['name']}" for p in src_props)
    typed_cols = []
    for p in c.properties:
        gen = c.generated_by(p)
        if gen:
            typed_cols.append(f"    {GEN_SOURCE[gen]} AS {p['name']}")
        elif str(p["physicalType"]).upper() == "STRING":
            typed_cols.append(f"    _raw.{p['name']} AS {p['name']}")
        else:
            typed_cols.append(f"    try_cast(_raw.{p['name']} AS {p['physicalType']}) AS {p['name']}")
    failed = ",\n".join(f"    CASE WHEN NOT {r.safe_expression} THEN {lit(r.name)} END" for r in rules)
    quarantine = [r.safe_expression for r in rules if r.action == "quarantine"]
    is_quarantined = ("NOT (\n    " + "\n    AND ".join(quarantine) + "\n  )") if quarantine else "false"
    expectations = ",\n".join(expectation(r, "silver", observe_only=True) for r in rules)
    columns = ",\n".join(column_ddl(c, p, cfg) for p in c.properties)
    product_spec = ",\n".join([columns, *pk_ddl(c)])
    select_cols = ",\n  ".join(p["name"] for p in c.properties)

    return (
        header(c, "SILVER casting, expectations, quarantine")
        + "\n-- 1. Type casting + contract verdict (private: not published to Unity Catalog).\n"
        "--    Every rule is an expectation here so its metrics land in the event log.\n"
        f"CREATE OR REFRESH PRIVATE STREAMING TABLE {checked} (\n{expectations}\n)\n"
        f"COMMENT {lit(f'Typed {c.table} records with the verdict of contract {c.id} v{c.version}.')}\n"
        "AS SELECT\n"
        "  typed.*,\n"
        f"  filter(array(\n{failed}\n  ), r -> r IS NOT NULL) AS _failed_rules,\n"
        f"  {is_quarantined} AS _is_quarantined\n"
        "FROM (\n"
        "  SELECT\n"
        + ",\n".join(typed_cols) + ",\n"
        "    _raw,\n"
        "    _rescued_data,\n"
        "    _ingested_at,\n"
        "    _source_file,\n"
        f"    {lit(c.version)} AS _contract_version\n"
        "  FROM (\n"
        f"    SELECT named_struct({raw_struct}) AS _raw, _rescued_data, _ingested_at, _source_file\n"
        f"    FROM STREAM({s['bronze']}.{c.table}_raw)\n"
        "  )\n"
        ") AS typed;\n"
        "\n-- 2. The data product: contract-compliant rows only.\n"
        f"CREATE OR REFRESH STREAMING TABLE {s['silver']}.{c.table} (\n{product_spec}\n)\n"
        f"COMMENT {lit(table_comment(c))}\n"
        f"{tblproperties(c, 'product')}\n"
        f"{row_filter_clause(c)}"
        "AS SELECT\n"
        f"  {select_cols}\n"
        f"FROM STREAM({checked})\n"
        "WHERE NOT _is_quarantined;\n"
        "\n-- 3. Quarantine: every violating row, the rules it broke (_failed_rules),\n"
        "--    the original payload (_raw) and the contract version that judged it.\n"
        f"CREATE OR REFRESH STREAMING TABLE {s['silver']}.{c.table}_quarantine\n"
        f"COMMENT {lit(f'Records that violated contract {c.id}. Contains unmasked raw values: producer access only.')}\n"
        f"{tblproperties(c, 'quarantine')}\n"
        "AS SELECT *\n"
        f"FROM STREAM({checked})\n"
        "WHERE _is_quarantined;\n"
    )


GEN_SOURCE = {"ingestion_timestamp": "_ingested_at", "source_file": "_source_file"}


def gold_sql(c: Contract, cfg: dict) -> str:
    s = cfg["schemas"]
    rules = c.rules()
    columns = [column_ddl(c, p, cfg) for p in c.properties]
    spec = ",\n".join([*columns, *(expectation(r, "gold", observe_only=False) for r in rules), *pk_ddl(c)])
    return (
        header(c, "GOLD business logic inside the contract envelope")
        + f"CREATE OR REFRESH MATERIALIZED VIEW {s['gold']}.{c.table} (\n{spec}\n)\n"
        f"COMMENT {lit(table_comment(c))}\n"
        f"{tblproperties(c, 'product')}\n"
        f"{row_filter_clause(c)}"
        f"AS\n-- ── business logic: {c.logic_path.relative_to(c.root).as_posix()} ──\n"
        f"{c.read_logic()};\n"
    )


def pipeline_sql(c: Contract, cfg: dict) -> dict[str, str]:
    """Relative path (under generated/pipelines/<domain>/) -> SQL."""
    if c.layer == "silver":
        return {f"bronze/{c.table}_raw.sql": bronze_sql(c, cfg), f"silver/{c.table}.sql": silver_sql(c, cfg)}
    return {f"gold/{c.table}.sql": gold_sql(c, cfg)}


# ── governance SQL (job task) ─────────────────────────────────────────────────
def _structs(items: list[dict], keys: tuple[str, ...]) -> str:
    if not items:
        return f"CAST(array() AS ARRAY<STRUCT<{', '.join(f'{k}: STRING' for k in keys)}>>)"
    rows = []
    for item in items:
        fields = ", ".join(f"{lit(k)}, {lit(item.get(k, '') if item.get(k) is not None else '')}" for k in keys)
        rows.append(f"named_struct({fields})")
    return "array(\n    " + ",\n    ".join(rows) + ")"


def _tags(tags: dict[str, str]) -> str:
    return ", ".join(f"{lit(k)} = {lit(v)}" for k, v in tags.items() if v)


def governance_sql(c: Contract, cfg: dict) -> str:
    s = cfg["schemas"]
    gov = s["governance"]
    product = f"{s[c.layer]}.{c.table}"
    kind = "STREAMING TABLE" if c.layer == "silver" else "MATERIALIZED VIEW"
    fresh = c.freshness()
    ret = c.sla("retention")
    out = [header(c, "GOVERNANCE registry, tags, certification, access"),
           "-- Runs as a SQL task after every pipeline run. Parameters: :catalog, :git_commit",
           "USE CATALOG IDENTIFIER(:catalog);", ""]

    # 1. registry
    sla_items = [{k: str(v) for k, v in sla.items()} for sla in c.doc.get("slaProperties") or []]
    out += [
        "-- 1. Contract registry: who owns this, who to call, what is promised",
        f"UPDATE {gov}.contract_registry SET is_current = false WHERE contract_id = {lit(c.id)};",
        f"DELETE FROM {gov}.contract_registry WHERE contract_id = {lit(c.id)} AND contract_version = {lit(c.version)};",
        f"INSERT INTO {gov}.contract_registry",
        "SELECT",
        f"  {lit(c.id)} AS contract_id, {lit(c.version)} AS contract_version, {lit(c.name)} AS name,",
        f"  {lit(c.status)} AS status, {lit(c.domain)} AS domain, {lit(c.layer)} AS layer,",
        f"  {lit(product)} AS table_name,",
        f"  {lit(str(c.description.get('purpose', '')).strip())} AS purpose,",
        f"  {lit(str(c.description.get('usage', '')).strip())} AS usage,",
        f"  {lit(str(c.description.get('limitations', '')).strip())} AS limitations,",
        f"  {lit(c.team_name)} AS owner_team,",
        f"  {_structs(c.members, ('username', 'name', 'role'))} AS team_members,",
        f"  {_structs(c.support, ('channel', 'tool', 'url'))} AS support,",
        f"  {_structs(sla_items, ('property', 'value', 'unit', 'element'))} AS sla,",
        f"  {_structs(c.roles, ('role', 'access', 'description'))} AS roles,",
        "  " + (f"array({', '.join(lit(i) for i in c.inputs)})" if c.inputs else "CAST(array() AS ARRAY<STRING>)") + " AS inputs,",
        "  :git_commit AS git_commit,",
        f"  {lit(c.rel_path)} AS contract_path,",
        "  current_timestamp() AS published_at,",
        "  true AS is_current,",
        f"  {lit(c.text)} AS contract_yaml;",
        "",
        f"UPDATE {gov}.contract_rules SET is_current = false WHERE contract_id = {lit(c.id)};",
        f"DELETE FROM {gov}.contract_rules WHERE contract_id = {lit(c.id)} AND contract_version = {lit(c.version)};",
        f"INSERT INTO {gov}.contract_rules VALUES",
        ",\n".join(
            f"  ({lit(c.id)}, {lit(c.version)}, {lit(product)}, {lit(r.name)}, {lit(r.scope)}, {lit(r.dimension)}, "
            f"{lit(r.expression)}, {lit(r.action)}, {lit(r.description)}, {str(r.implicit).lower()}, true)"
            for r in c.rules()) + ";",
        "",
    ]

    # 2. tags
    table_tags = {
        "contract_id": c.id, "contract_version": c.version, "contract_status": c.status,
        "data_domain": c.domain, "data_product": c.name, "layer": c.layer,
        "owner_team": c.team_name, "support_channel": c.primary_channel.get("channel", ""),
        "sla_freshness": fresh.label if fresh else "",
        "sla_retention": f"{ret['value']}{ret.get('unit', '')}" if ret else "",
    }
    out += ["-- 2. Tags: contract metadata on the table, classification on the columns",
            f"ALTER {kind} {product} SET TAGS ({_tags(table_tags)});"]
    for p in c.properties:
        col_tags = c.column_tags(p)
        if col_tags:
            out.append(f"ALTER {kind} {product} ALTER COLUMN {p['name']} SET TAGS ({_tags(col_tags)});")
    if c.layer == "silver":
        for suffix, schema, role in (("_raw", s["bronze"], "bronze"), ("_quarantine", s["silver"], "quarantine")):
            tags = {"contract_id": c.id, "layer": role, "owner_team": c.team_name}
            out.append(f"ALTER STREAMING TABLE {schema}.{c.table}{suffix} SET TAGS ({_tags(tags)});")
    if cfg.get("features", {}).get("certification_badge"):
        badge = {"active": "certified", "deprecated": "deprecated", "retired": "deprecated"}.get(c.status)
        out.append("-- Contract status drives the certified / deprecated badge in Catalog Explorer")
        out.append(f"SET TAG ON TABLE {product} `system.certification_status` = `{badge}`;" if badge
                   else f"UNSET TAG ON TABLE {product} `system.certification_status`;")
    out.append("")

    # 3. access
    out.append("-- 3. Access: contract roles -> Unity Catalog grants (groups must exist)")
    readers = c.role_groups("read")
    writers = c.role_groups("write")
    for group in readers + writers:
        out.append(f"GRANT SELECT ON TABLE {product} TO {ident(group)};")
    if c.layer == "silver":
        for group in writers:
            out.append(f"GRANT SELECT ON TABLE {s['silver']}.{c.table}_quarantine TO {ident(group)};")
            out.append(f"GRANT SELECT ON TABLE {s['bronze']}.{c.table}_raw TO {ident(group)};")
    return "\n".join(out) + "\n"


# ── SLA SQL (job task) ────────────────────────────────────────────────────────
def sla_sql(c: Contract, cfg: dict) -> str:
    s = cfg["schemas"]
    gov = s["governance"]
    product = f"{s[c.layer]}.{c.table}"
    channel = c.primary_channel
    common = f"{lit(c.id)}, {lit(c.version)}, {lit(product)}"
    tail = f"{lit(c.team_name)}, {lit(channel.get('channel', ''))}, {lit(channel.get('url', ''))}"
    out = [header(c, "SLA and table-level checks"),
           "-- Runs as a SQL task after governance. Parameters: :catalog, :run_id",
           "USE CATALOG IDENTIFIER(:catalog);", ""]

    fresh = c.freshness()
    if fresh:
        out += [
            f"-- Freshness: max({fresh.column}) must be at most {fresh.label} old",
            f"INSERT INTO {gov}.contract_sla_results",
            f"SELECT :run_id, current_timestamp(), {common}, 'freshness', 'freshness', {lit('<= ' + fresh.label)},",
            "       coalesce(concat(CAST(round(age_s / 3600.0, 2) AS STRING), 'h'), 'no data'),",
            f"       coalesce(age_s <= {int(fresh.seconds)}, false), {tail}",
            f"FROM (SELECT timestampdiff(SECOND, max({fresh.column}), current_timestamp()) AS age_s",
            f"      FROM {s[c.layer]}.{fresh.table});",
            "",
        ]
    for check in c.sql_checks():
        out += [
            f"-- {check.name}: {check.description or check.expected}",
            f"INSERT INTO {gov}.contract_sla_results",
            f"SELECT :run_id, current_timestamp(), {common}, {lit(check.name)}, 'sql', {lit(check.expected)},",
            "       coalesce(CAST(measured AS STRING), 'null'),",
            f"       coalesce({check.condition('measured')}, false), {tail}",
            f"FROM (SELECT (\n{check.query}\n) AS measured);",
            "",
        ]
    contact = f"Owner: {c.team_name}. Contact: {channel.get('channel', '')} {channel.get('url', '')}".strip()
    out += [
        "-- Fail the task (and notify the contract owner) if anything in this run breached",
        "SELECT CASE WHEN count_if(NOT passed) > 0 THEN raise_error(concat(",
        f"         {lit(f'Data contract {c.id} v{c.version} breached: ')},",
        "         array_join(collect_list(CASE WHEN NOT passed THEN check_name END), ', '),",
        f"         {lit('. ' + contact)})) END AS verdict",
        f"FROM {gov}.contract_sla_results",
        f"WHERE run_id = :run_id AND contract_id = {lit(c.id)};",
    ]
    return "\n".join(out) + "\n"


def observability_sql(domain: str, contracts: list[Contract], cfg: dict) -> str:
    """Ready-to-run monitoring queries for one domain (not run by the job)."""
    s = cfg["schemas"]
    out = [
        "-- " + "=" * 76,
        f"-- GENERATED by contractctl: monitoring queries for domain {domain}",
        "-- Not run by the job. Open in the SQL editor, select your catalog, and run,",
        "-- or build an AI/BI dashboard or SQL alerts on them.",
        "-- Do not edit: change the contracts and run `contractctl generate`.",
        "-- " + "=" * 76,
        "",
        "-- Compliance per contract rule: pipeline event log joined with the contract rules",
        "WITH dq AS (",
        "  SELECT timestamp, explode(from_json(",
        "           details:flow_progress.data_quality.expectations,",
        "           'ARRAY<STRUCT<name: STRING, dataset: STRING, passed_records: BIGINT, failed_records: BIGINT>>')) AS e",
        f"  FROM {s['governance']}.{domain}_pipeline_event_log",
        "  WHERE event_type = 'flow_progress'",
        "    AND details:flow_progress.data_quality.expectations IS NOT NULL",
        ")",
        "SELECT r.table_name, e.name AS rule_name, r.on_violation, r.dimension, r.contract_version,",
        "       SUM(e.passed_records) AS passed, SUM(e.failed_records) AS failed,",
        "       ROUND(100 * SUM(e.failed_records) / NULLIF(SUM(e.passed_records + e.failed_records), 0), 1) AS pct_failed",
        "FROM dq",
        f"JOIN {s['governance']}.contract_rules r ON r.rule_name = e.name AND r.is_current",
        "GROUP BY ALL",
        "ORDER BY failed DESC;",
    ]
    for c in sorted(contracts, key=lambda c: c.table):
        if c.layer != "silver":
            continue
        q = f"{s['silver']}.{c.table}_quarantine"
        out += [
            "",
            f"-- {c.table}: which rules are broken most, per contract version",
            "SELECT _contract_version, rule_name, count(*) AS records",
            f"FROM (SELECT _contract_version, explode(_failed_rules) AS rule_name FROM {q})",
            "GROUP BY ALL",
            "ORDER BY records DESC;",
            "",
            f"-- {c.table}: the quarantined records, newest first",
            "SELECT _failed_rules, _raw, _rescued_data, _source_file, _contract_version, _ingested_at",
            f"FROM {q}",
            "ORDER BY _ingested_at DESC",
            "LIMIT 100;",
        ]
    return "\n".join(out) + "\n"
