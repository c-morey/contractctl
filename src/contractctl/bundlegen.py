"""
Bundle resource generation: one pipeline and one job per domain.

  pipeline  all generated SQL of the domain, serverless, event log published to UC,
            failure notifications to the platform team
  job       run pipeline -> per contract: governance (SQL task) -> SLA checks (SQL task);
            each contract's tasks notify that contract's support e-mail on failure;
            schedule derived from the tightest `frequency` SLA in the domain
"""
from __future__ import annotations

import copy
from collections import defaultdict

import yaml

from .model import Contract

HEADER = ("# GENERATED by contractctl from the contracts in {domain_dir}.\n"
          "# Do not edit: change the contracts or contractctl.yml and run `contractctl generate`.\n")


def _schedule(contracts: list[Contract]) -> dict | None:
    freqs = [f for f in (c.frequency_seconds() for c in contracts) if f]
    if not freqs:
        return None
    seconds = min(freqs)
    if seconds % 86400 == 0:
        return {"periodic": {"interval": int(seconds // 86400), "unit": "DAYS"}}
    return {"periodic": {"interval": max(1, int(seconds // 3600)), "unit": "HOURS"}}


def domain_resources(domain: str, contracts: list[Contract], sql_files: list[str], cfg: dict) -> str:
    s = cfg["schemas"]
    notif = cfg.get("notifications", {})
    platform_email = notif.get("platform_email")
    teams = notif.get("teams_destination_id")
    rel = "../../"  # resources/generated -> repo root
    pipeline_key = f"{domain}_data_products"

    pipeline = {
        "name": f"{domain}-data-products",
        "catalog": "${var.catalog}",
        "schema": s["silver"],
        "serverless": bool(cfg.get("pipeline", {}).get("serverless", True)),
        "continuous": bool(cfg.get("pipeline", {}).get("continuous", False)),
        "libraries": [{"file": {"path": rel + f}} for f in sql_files],
        "configuration": {
            "contracts.catalog": "${var.catalog}",
            "contracts.landing": f"/Volumes/${{var.catalog}}/{s['bronze']}/{cfg['landing_volume']}",
        },
        "event_log": {"catalog": "${var.catalog}", "schema": s["governance"], "name": f"{domain}_pipeline_event_log"},
    }
    if platform_email:
        pipeline["notifications"] = [{
            "email_recipients": [platform_email],
            "alerts": ["on-update-failure", "on-update-fatal-failure", "on-flow-failure"],
        }]

    tasks = [{
        "task_key": f"run_{domain}_pipeline",
        "description": "Ingest, cast, enforce expectations, quarantine, build gold",
        "pipeline_task": {"pipeline_id": f"${{resources.pipelines.{pipeline_key}.id}}"},
    }]
    for c in contracts:
        recipients = sorted(set(c.support_emails + ([platform_email] if platform_email else [])))
        notify = {"email_notifications": {"on_failure": recipients}} if recipients else {}
        if teams:
            notify["webhook_notifications"] = {"on_failure": [{"id": teams}]}
        tasks.append({
            "task_key": f"govern_{c.table}",
            "description": f"Registry, tags, certification and grants for {c.id} v{c.version}",
            "depends_on": [{"task_key": f"run_{domain}_pipeline"}],
            "sql_task": {
                "warehouse_id": "${var.warehouse_id}",
                "file": {"path": rel + f"{cfg['generated_dir']}/governance/{domain}/{c.table}.sql", "source": "WORKSPACE"},
                "parameters": {"catalog": "${var.catalog}", "git_commit": "${bundle.git.commit}"},
            },
            **copy.deepcopy(notify),
        })
        tasks.append({
            "task_key": f"verify_{c.table}",
            "description": f"SLA and table-level checks for {c.id} v{c.version}; fails on breach",
            "depends_on": [{"task_key": f"govern_{c.table}"}],
            "sql_task": {
                "warehouse_id": "${var.warehouse_id}",
                "file": {"path": rel + f"{cfg['generated_dir']}/sla/{domain}/{c.table}.sql", "source": "WORKSPACE"},
                "parameters": {"catalog": "${var.catalog}", "run_id": "{{task.run_id}}"},
            },
            **copy.deepcopy(notify),
        })

    job = {
        "name": f"{domain}-data-contracts",
        "description": f"Enforce, publish and verify the data contracts of the {domain} domain",
        "max_concurrent_runs": 1,
        "tasks": tasks,
    }
    schedule = _schedule(contracts) if cfg.get("job", {}).get("schedule_from_sla", True) else None
    if schedule and not pipeline["continuous"]:
        job["trigger"] = schedule
    if platform_email:
        job["email_notifications"] = {"on_failure": [platform_email]}

    doc = {"resources": {"pipelines": {pipeline_key: pipeline}, "jobs": {f"{domain}_data_contracts": job}}}
    body = yaml.safe_dump(doc, sort_keys=False, width=120, default_flow_style=False)
    return HEADER.format(domain_dir=f"{cfg['data_products_dir']}/{domain}") + body


def group_by_domain(contracts: list[Contract]) -> dict[str, list[Contract]]:
    groups: dict[str, list[Contract]] = defaultdict(list)
    for c in contracts:
        groups[c.domain].append(c)
    return dict(sorted(groups.items()))
